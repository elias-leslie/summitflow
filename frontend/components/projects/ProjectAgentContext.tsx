'use client'

import { useQuery } from '@tanstack/react-query'
import { ExternalLink } from 'lucide-react'
import type { ReactNode } from 'react'
import {
  type AgentContextItem,
  buildAgentHubUiUrl,
  fetchProject,
  fetchProjectAgentContext,
} from '@/lib/api'
import { STALE_STANDARD } from '@/lib/polling'
import { safeExternalHttpUrl } from '@/lib/project-registration'
import { getErrorMessage } from '@/lib/utils'
import { Badge } from '../ui/badge'
import { Button } from '../ui/button'
import { Card, CardContent, CardHeader, CardTitle } from '../ui/card'

const AGENT_HUB_PROJECT_ID = 'agent-hub'

const KIND_LABELS: Record<AgentContextItem['kind'], string> = {
  prompt: 'Prompt',
  memory: 'Memory',
  project_index: 'Project index',
  continuity: 'Continuity',
  tool_capabilities: 'Tools',
  computed: 'Generated',
}

const SURFACE_LABELS: Record<string, string> = {
  claude_code: 'Claude Code',
  codex: 'Codex',
}

function formatTokens(tokens: number): string {
  return `~${tokens.toLocaleString('en-US')} tokens`
}

function plural(count: number, word: string): string {
  return `${count} ${word}${count === 1 ? '' : 's'}`
}

function GeneratedNote({ item }: { item: AgentContextItem }) {
  if (item.kind === 'project_index') return <>Generated from .index.yaml</>
  return <>Generated by Agent Hub</>
}

function AgentContextRow({
  item,
  agentHubUrl,
}: {
  item: AgentContextItem
  agentHubUrl: string | null
}) {
  const editUrl = buildAgentHubUiUrl(agentHubUrl, item.edit_path)
  return (
    <li className="flex flex-col gap-1 border-t border-slate-800/70 py-2 first:border-t-0 sm:flex-row sm:items-start sm:justify-between sm:gap-4">
      <div className="min-w-0">
        <div className="flex flex-wrap items-center gap-2">
          <Badge variant={item.group === 'project' ? 'phosphor' : 'slate'}>
            {KIND_LABELS[item.kind] ?? item.kind}
          </Badge>
          <span className="break-words text-sm text-slate-200">
            {item.title}
          </span>
          {item.required && (
            <span className="text-2xs uppercase tracking-wide text-slate-500">
              required
            </span>
          )}
        </div>
        <p className="mt-0.5 break-words text-xs text-slate-500">
          {item.reason}
          {item.facts.length > 0 && <> · {item.facts.join(', ')}</>}
        </p>
      </div>
      <div className="flex shrink-0 items-center gap-3 text-xs">
        <span
          className="font-mono text-slate-400"
          title={`${item.char_count.toLocaleString('en-US')} characters`}
        >
          {formatTokens(item.estimated_tokens)}
        </span>
        {editUrl ? (
          <a
            href={editUrl}
            target="_blank"
            rel="noreferrer"
            aria-label={`Edit ${item.title} in Agent Hub`}
            className="inline-flex items-center gap-1 rounded text-phosphor-400 hover:text-phosphor-300 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-phosphor-500/60"
          >
            <ExternalLink className="h-3 w-3" aria-hidden="true" />
            Edit in Agent Hub
          </a>
        ) : item.edit_path ? (
          <span className="text-slate-500">Agent Hub link unavailable</span>
        ) : (
          <span className="text-slate-500">
            <GeneratedNote item={item} />
          </span>
        )}
      </div>
    </li>
  )
}

interface ProjectAgentContextProps {
  projectId: string
}

export function ProjectAgentContext({ projectId }: ProjectAgentContextProps) {
  const {
    data: context,
    isLoading,
    error,
    refetch,
    isFetching,
  } = useQuery({
    queryKey: ['project-agent-context', projectId],
    queryFn: () => fetchProjectAgentContext(projectId),
    staleTime: STALE_STANDARD,
  })
  const { data: agentHubProject } = useQuery({
    queryKey: ['project', AGENT_HUB_PROJECT_ID],
    queryFn: () => fetchProject(AGENT_HUB_PROJECT_ID),
    staleTime: STALE_STANDARD,
  })
  const agentHubUrl = safeExternalHttpUrl(
    agentHubProject?.public_url || agentHubProject?.base_url || '',
  )

  const retry = (
    <Button
      variant="secondary"
      size="sm"
      disabled={isFetching}
      onClick={() => void refetch()}
    >
      {isFetching ? 'Retrying...' : 'Retry'}
    </Button>
  )

  let body: ReactNode
  if (isLoading) {
    body = (
      <p role="status" className="text-sm text-slate-400">
        Loading agent context...
      </p>
    )
  } else if (error || !context) {
    body = (
      <div className="space-y-3">
        <p role="alert" className="break-words text-sm text-rose-300">
          {getErrorMessage(
            error,
            'Could not load agent context from Agent Hub.',
          )}
        </p>
        {retry}
      </div>
    )
  } else if (context.status === 'failed') {
    body = (
      <div className="space-y-3">
        <p role="alert" className="break-words text-sm text-rose-300">
          Agent Hub could not assemble this project's startup context
          {context.failure ? `: ${context.failure.message}` : '.'}
        </p>
        {retry}
      </div>
    )
  } else {
    const projectItems = context.items.filter(
      (item) => item.group === 'project',
    )
    const globalItems = context.items.filter((item) => item.group === 'global')
    const { totals, withheld } = context
    body = (
      <div className="space-y-4">
        <p className="text-xs text-slate-400">
          <span className="font-mono text-slate-200">
            {formatTokens(totals.delivered_tokens)}
          </span>{' '}
          in {plural(totals.items + withheld.count, 'item')} for a new{' '}
          {SURFACE_LABELS[context.consumer_surface] ?? context.consumer_surface}{' '}
          session. Read-only here; Agent Hub owns and edits it.
        </p>

        <section aria-labelledby="agent-context-project">
          <h3
            id="agent-context-project"
            className="flex flex-wrap items-baseline gap-2 text-sm font-semibold text-slate-100"
          >
            Project-specific
            <span className="text-xs font-normal text-slate-500">
              {plural(totals.project_items, 'item')} ·{' '}
              {formatTokens(totals.project_tokens)}
            </span>
          </h3>
          {projectItems.length > 0 ? (
            <ul className="mt-1">
              {projectItems.map((item) => (
                <AgentContextRow
                  key={`${item.order}:${item.source_id}`}
                  item={item}
                  agentHubUrl={agentHubUrl}
                />
              ))}
            </ul>
          ) : (
            <p className="mt-1 text-sm text-slate-400">
              Nothing project-specific is delivered at startup.
            </p>
          )}
        </section>

        {withheld.count > 0 && (
          <p className="text-xs text-slate-500">
            {withheld.count} sensitive{' '}
            {withheld.count === 1 ? 'memory' : 'memories'} not listed (
            {formatTokens(withheld.estimated_tokens)}).
          </p>
        )}

        <details className="group rounded-md border border-slate-800/80 bg-slate-950/40">
          <summary className="cursor-pointer select-none px-3 py-2 text-sm text-slate-300 hover:text-slate-100 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-phosphor-500/60">
            Global context
            <span className="ml-2 text-xs text-slate-500">
              {plural(totals.global_items, 'item')} ·{' '}
              {formatTokens(totals.global_tokens)}
            </span>
          </summary>
          <div className="px-3 pb-2">
            {globalItems.length > 0 ? (
              <ul>
                {globalItems.map((item) => (
                  <AgentContextRow
                    key={`${item.order}:${item.source_id}`}
                    item={item}
                    agentHubUrl={agentHubUrl}
                  />
                ))}
              </ul>
            ) : (
              <p className="py-2 text-sm text-slate-400">
                No global context is delivered.
              </p>
            )}
          </div>
        </details>
      </div>
    )
  }

  const manageUrl = buildAgentHubUiUrl(
    agentHubUrl,
    context?.manage_path ?? '/runtime-context',
  )

  return (
    <Card className="mx-auto w-full max-w-[1100px] min-w-0 border-slate-800/80 bg-slate-950/55">
      <CardHeader className="flex flex-row flex-wrap items-center justify-between gap-3 pb-3">
        <CardTitle className="text-base">Agent context</CardTitle>
        {manageUrl && (
          <a
            href={manageUrl}
            target="_blank"
            rel="noreferrer"
            className="inline-flex items-center gap-1 rounded text-xs text-slate-400 hover:text-phosphor-300 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-phosphor-500/60"
          >
            <ExternalLink className="h-3 w-3" aria-hidden="true" />
            Runtime context in Agent Hub
          </a>
        )}
      </CardHeader>
      <CardContent>{body}</CardContent>
    </Card>
  )
}
